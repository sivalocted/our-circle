export type AlbumVideo = AlbumVideoItem;

const STORAGE_KEY = 'our_circle_custom_album_videos';

export function getCustomAlbumVideos(): AlbumVideoItem[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveCustomAlbumVideos(videos: AlbumVideoItem[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(videos));
  } catch {
    // Ignore storage quota
  }
}

export function getAllSortedAlbumVideos(): AlbumVideoItem[] {
  const custom = getCustomAlbumVideos();
  const map = new Map<string, AlbumVideoItem>();

  DEVELOPMENT_ALBUM_VIDEOS.forEach((v) => map.set(v.id, v));
  custom.forEach((v) => map.set(v.id, v));

  return Array.from(map.values()).sort((a, b) => a.timestamp - b.timestamp);
}

export function addAlbumVideo(videoInput: Partial<AlbumVideoItem>): AlbumVideoItem {
  const existing = getAllSortedAlbumVideos();
  const nextIndex = existing.length + 1;
  const now = new Date();

  const isPortrait = (videoInput.height || 720) > (videoInput.width || 1280);
  const w = videoInput.width || (isPortrait ? 720 : 1280);
  const h = videoInput.height || (isPortrait ? 1280 : 720);
  const ar = w / h;
  const baseUrl = videoInput.baseUrl || videoInput.videoUrl || '';
  const isGoogleMedia = baseUrl.includes('googleusercontent.com');

  const newVideo: AlbumVideoItem = {
    id: videoInput.id || ('album_vid_' + Date.now()),
    albumIndex: videoInput.albumIndex || nextIndex,
    baseUrl,
    videoUrl: videoInput.videoUrl || '',
    posterUrl: videoInput.posterUrl || (isGoogleMedia ? baseUrl + '=w1920-h1080-no' : ''),
    thumbUrl: videoInput.thumbUrl || (isGoogleMedia ? baseUrl + '=w400-h400-c' : ''),
    title: videoInput.title?.trim() || 'Untitled video',
    timestamp: videoInput.timestamp || now.getTime(),
    dateFormatted: videoInput.dateFormatted?.trim() || 'Undated',
    timeFormatted: videoInput.timeFormatted?.trim() || '',
    year: videoInput.year ?? 0,
    yearMonth: videoInput.yearMonth || 'Undated',
    width: w,
    height: h,
    aspectRatio: ar,
    resolutionLabel: videoInput.resolutionLabel || 'Video',
    isVertical: isPortrait,
    hasAudio: true,
    audioCodec: 'aac',
    people: videoInput.people && videoInput.people.length > 0 ? videoInput.people : [],
    isNew: true,
  };

  const custom = getCustomAlbumVideos().filter((v) => v.id !== newVideo.id);
  custom.push(newVideo);
  saveCustomAlbumVideos(custom);

  return newVideo;
}

